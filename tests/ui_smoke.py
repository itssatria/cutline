"""Optional UI smoke test: runs the real style.css + dnd.js in Chromium.
Setup:  pip install playwright pillow ; playwright install chromium
Run:    python tests/ui_smoke.py   (screenshots go to a temp folder that is printed at the end)"""
import json
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import ui_harness as H
from cutline import gridhtml as G
from playwright.sync_api import sync_playwright
WORK = Path(tempfile.mkdtemp(prefix='cutline_ui_'))
imgs = H.make_images(WORK / 'imgs', 10)
H.build(WORK / 'page.html', imgs)
R = {}
def ok(name, cond, extra=''):
    R[name] = bool(cond); print(('PASS ' if cond else 'FAIL ') + name, extra)
def rect(pg, sel):
    return pg.evaluate("(s)=>{const e=document.querySelector(s); if(!e) return null; const b=e.getBoundingClientRect(); return {l:b.left,t:b.top,w:b.width,h:b.height,r:b.right,b:b.bottom}}", sel)
def val(pg, sel): return pg.input_value(sel + ' textarea').rsplit('|',1)[0]
S = '#page-story '
with sync_playwright() as p:
    b = p.chromium.launch(); pg = b.new_page(viewport={'width':1280,'height':720})
    errs=[]; pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.goto((WORK / 'page.html').as_uri()); pg.wait_for_timeout(700)
    pg.click('#tab-story'); pg.wait_for_timeout(700)
    vh = 720
    bot = rect(pg, '#sb-bottom'); ft = rect(pg, '#app-footer')
    ok('bottom bar fully visible above footer', bot['b'] <= ft['t'] + 1, f"bottom.b={bot['b']:.0f} footer.t={ft['t']:.0f}")
    ok('bottom bar is one line', rect(pg, '#sb-bottom')['h'] < 60, str(rect(pg, '#sb-bottom')['h']))
    ok('Sort toolbar button visible without scrolling', rect(pg, S+'[data-act=sort]')['b'] < vh)
    ok('the window itself does not scroll (single scrollbar)', pg.evaluate('document.documentElement.scrollHeight') <= vh + 1, str(pg.evaluate('document.documentElement.scrollHeight')))
    scrollers = pg.evaluate("""() => Array.from(document.querySelectorAll('#page-story .mainc *')).filter(e => ['auto','scroll'].includes(getComputedStyle(e).overflowY) && e.scrollHeight > e.clientHeight + 1).map(e => e.id || e.className)""")
    ok('exactly one scroll area inside the gallery panel', scrollers == ['sb-scroll'] or scrollers == [], str(scrollers))
    ok('sidebar scrolls inside itself when taller than the window', pg.evaluate("(() => { const e = document.querySelector('#page-story .side'); return e.scrollHeight > e.clientHeight + 10 && getComputedStyle(e).overflowY === 'auto'; })()"))
    ok('header stays at top', abs(rect(pg, '#app-header')['t']) < 2)
    # thumbnails keep their own orientation
    shapes = pg.evaluate("""() => Array.from(document.querySelectorAll('#sb-grid .sb-frame img')).slice(0, 3).map(i => { const b = i.getBoundingClientRect(); return [b.width / b.height, i.naturalWidth / i.naturalHeight]; })""")
    ok('thumbnails keep original shape (portrait / landscape / square)', all(abs(a - b) / b < 0.06 for a, b in shapes) and shapes[0][0] < 1 < shapes[1][0], str([[round(x, 2) for x in p] for p in shapes]))
    ok('portrait thumbnail is narrower than landscape', shapes[0][0] < shapes[1][0])
    pg.screenshot(path=str(WORK / 's_story.png'))
    # icon buttons
    icons = pg.evaluate("""() => ['[data-act=theme]', '[data-act=ft-check]', '[data-act=ft-about]'].map(s => { const e = document.querySelector(s); const b = e.getBoundingClientRect(); const v = e.querySelector('svg'); const vb = v ? v.getBoundingClientRect() : {width: 0}; return [b.width, b.height, e.innerText.trim(), vb.width]; })""")
    ok('theme / update / about are icon buttons (svg, no text)', all(w >= 30 and t == '' and sv > 10 for w, h, t, sv in icons), str(icons))
    dark0 = pg.evaluate("document.body.classList.contains('dark')")
    pg.click('[data-act=theme]'); pg.wait_for_timeout(150)
    ok('theme icon toggles light / dark', pg.evaluate("document.body.classList.contains('dark')") != dark0)
    pg.screenshot(path=str(WORK / 's_light.png'))
    pg.click('[data-act=theme]')
    pg.click('[data-act=ft-check]'); pg.wait_for_timeout(150)
    ok('update icon posts to footer bridge', val(pg, '#ft-bridge') == 'check')
    pg.click('[data-act=ft-about]'); pg.wait_for_timeout(150)
    ok('about icon posts to footer bridge', val(pg, '#ft-bridge') == 'about')
    # favicon: ours wins over the framework's
    fav = pg.evaluate("Array.from(document.querySelectorAll('link[rel~=icon]')).map(l => [l.id, l.href.slice(0, 22)])")
    ok('favicon is the Cutline logo', fav == [['cutline-icon', 'data:image/png;base64,']] and pg.title() == 'Cutline', str(fav))
    # blur thumbnails
    pg.evaluate("document.body.classList.add('blur-thumbs')")
    f0 = pg.locator('.sb-frame').nth(0)
    blurred = pg.evaluate("getComputedStyle(document.querySelector('#sb-grid .sb-frame img')).filter")
    f0.hover(); pg.wait_for_timeout(400)
    revealed = pg.evaluate("getComputedStyle(document.querySelector('#sb-grid .sb-frame img')).filter")
    ok('blur-thumbs blurs thumbnails and hover reveals', 'blur' in blurred and revealed == 'none', f"{blurred} / {revealed}")
    pg.evaluate("document.body.classList.remove('blur-thumbs')"); pg.mouse.move(5, 300)
    pg.click(S+'[data-act=sort]'); pg.wait_for_timeout(200)
    ok('toolbar Sort posts sort bridge', pg.input_value('#sort-bridge textarea').startswith('go|'))
    w0 = rect(pg, S+'.mainc')['w']
    ok('Show-sidebar button hidden while the sidebar is visible', not pg.is_visible(S+'.show-side'))
    ok('Hide-sidebar button is inside the sidebar', pg.evaluate("!!document.querySelector('#page-story .side [data-act=toggle-side]')"))
    pg.click(S+'.side [data-act=toggle-side]'); pg.wait_for_timeout(300)
    ok('Hide sidebar widens gallery', rect(pg, S+'.mainc')['w'] > w0 + 250 and pg.evaluate("getComputedStyle(document.querySelector('#page-story .side')).display")=='none')
    ok('Show-sidebar button appears in the toolbar', pg.is_visible(S+'.show-side'))
    pg.screenshot(path=str(WORK / 's_hidden.png'))
    pg.click(S+'.show-side'); pg.wait_for_timeout(200)
    ok('Show sidebar brings it back', pg.evaluate("getComputedStyle(document.querySelector('#page-story .side')).display") != 'none')
    pg.focus('#sort-btn')
    fr = pg.locator('.sb-frame').nth(3).bounding_box()
    pg.mouse.move(fr['x']+30, fr['y']+30); pg.keyboard.press('Space'); pg.wait_for_timeout(400)
    ok('Space opens panel even with a button focused', pg.evaluate("document.body.classList.contains('pv-open')"))
    key = val(pg, '#preview-bridge')
    ok('Space posts preview key', key == 'story:3:4:10', key)
    kind, idx, pos, tot = key.split(':')
    pg.evaluate("(h)=>{document.querySelector('#pv-data').innerHTML = h}", G.preview_panel(kind, int(idx), imgs[int(idx)], int(pos), int(tot)))
    pg.wait_for_timeout(900)
    pv = rect(pg, '#cutline-pv')
    ok('gallery narrows to make room for the panel', rect(pg, S+'.mainc')['r'] <= pv['l'] + 1, f"mainc.r={rect(pg, S+'.mainc')['r']:.0f} panel.l={pv['l']:.0f}")
    ok('preview panel visible inside window', pv and pv['r'] <= 1281 and pv['w'] > 300 and pg.evaluate("getComputedStyle(document.querySelector('#cutline-pv')).visibility")=='visible', str(pv))
    ok('panel shows the image', pg.evaluate("!!document.querySelector('#cutline-pv .pv-img')"))
    pg.screenshot(path=str(WORK / 's_preview.png'))
    pg.keyboard.press('ArrowRight'); pg.wait_for_timeout(300)
    ok('arrow key requests next image', val(pg, '#preview-bridge').startswith('story:4:5:10'), val(pg, '#preview-bridge'))
    pg.keyboard.press('Space'); pg.wait_for_timeout(500)
    ok('Space closes panel', not pg.evaluate("document.body.classList.contains('pv-open')"))
    fr = pg.locator('.sb-frame').nth(6).bounding_box()
    pg.mouse.dblclick(fr['x']+40, fr['y']+40); pg.wait_for_timeout(300)
    ok('double-click opens preview', pg.evaluate("document.body.classList.contains('pv-open')") and val(pg, '#preview-bridge').startswith('story:6:7:10'))
    pg.keyboard.press('Escape'); pg.wait_for_timeout(400)
    ok('Esc closes panel', not pg.evaluate("document.body.classList.contains('pv-open')"))
    pg.locator('.sb-frame').nth(1).click(); pg.locator('.sb-frame').nth(3).click(modifiers=['Control']); pg.locator('.sb-frame').nth(5).click(modifiers=['Shift'])
    n_sel = pg.evaluate("document.querySelectorAll('.sb-frame.sel').length")
    ok('click / ctrl / shift select', n_sel >= 3, str(n_sel))
    pg.click(S+'[data-act=pin-ends]'); pg.wait_for_timeout(200)
    ok('Pin ends locks first and last', val(pg, '#lock-bridge') == '[0,9]', val(pg, '#lock-bridge'))
    pg.locator('.sb-frame').nth(4).hover(); pg.locator('.sb-frame').nth(4).locator('.sb-lock').click(); pg.wait_for_timeout(200)
    ok('lock icon toggles one frame', val(pg, '#lock-bridge') == '[0,4,9]', val(pg, '#lock-bridge'))
    pg.mouse.move(5, 300); pg.screenshot(path=str(WORK / 's_locks.png'))
    pg.click(S+'[data-act=unlock-all]'); pg.wait_for_timeout(200)
    ok('Unlock all', val(pg, '#lock-bridge') == '[]')
    pg.locator('.sb-frame').nth(0).click(); pg.locator('.sb-frame').nth(1).click(modifiers=['Control'])
    pg.locator('.sb-frame').nth(0).drag_to(pg.locator('.sb-frame').nth(7)); pg.wait_for_timeout(300)
    order = val(pg, '#order-bridge').split(',')
    ok('dragging a multi-selection moves them together', len(order)==10 and order.index('0') == order.index('1') - 1 and order.index('0') > 3, ','.join(order))
    pg.click('#tab-anim'); pg.wait_for_timeout(600)
    ok('animatic: no needless page scroll', pg.evaluate('document.documentElement.scrollHeight') <= 721, str(pg.evaluate('document.documentElement.scrollHeight')))
    ok('animatic: bottom bar visible', rect(pg,'#am-bottom')['b'] <= rect(pg,'#app-footer')['t'] + 1)
    pg.locator('.am-ta').nth(0).fill('Opening shot'); pg.locator('.am-ta').nth(0).blur(); pg.wait_for_timeout(200)
    am = json.loads(val(pg, '#am-bridge'))
    ok('typing story text posts save with all texts', am['act']=='save' and am['texts']['0']=='Opening shot' and am['texts']['2']=='The hero wakes.')
    pg.click('[data-act=am-gen]'); pg.wait_for_timeout(200)
    ok('Generate story posts gen', json.loads(val(pg, '#am-bridge'))['act']=='gen')
    pg.fill('.am-secs','4'); pg.wait_for_timeout(700)
    ok('runtime updates live', '4 s each' in pg.inner_text('#am-info') and '0:40' in pg.inner_text('#am-info'), pg.inner_text('#am-info'))
    pg.screenshot(path=str(WORK / 's_anim.png'))
    pg.click('#tab-dup'); pg.wait_for_timeout(500)
    pg.locator('.dp-group >> nth=0').locator('[data-act=compare]').click(); pg.wait_for_timeout(300)
    ok('Compare click opens panel and posts', pg.evaluate("document.body.classList.contains('pv-open')") and val(pg, '#compare-bridge') == '{"g":0,"a":0,"b":1}', val(pg, '#compare-bridge'))
    pg.evaluate("(h)=>{document.querySelector('#pv-data').innerHTML = h}", G.compare_panel(0, imgs, [0,1,2], 0, 1)); pg.wait_for_timeout(900)
    st = rect(pg, '#cutline-pv .cmp-stage')
    ok('compare slider shown', st and st['w'] > 200 and st['h'] > 50, str(st))
    pg.mouse.move(st['l']+st['w']*0.5, st['t']+st['h']/2); pg.mouse.down(); pg.mouse.move(st['l']+st['w']*0.2, st['t']+st['h']/2, steps=4); pg.mouse.up()
    pos = pg.evaluate("document.querySelector('#cutline-pv .cmp-stage').style.getPropertyValue('--pos')")
    ok('dragging the divider changes position', pos.endswith('%') and 15 < float(pos[:-1]) < 25, pos)
    pg.screenshot(path=str(WORK / 's_compare.png'))
    pg.keyboard.press('Escape'); pg.wait_for_timeout(300)
    pg.evaluate("document.querySelector('#compare-bridge textarea').value=''")
    cd = pg.locator('.dp-card').nth(1).bounding_box(); pg.mouse.move(cd['x']+20, cd['y']+20); pg.keyboard.press('c'); pg.wait_for_timeout(300)
    ok('C key compares hovered card', val(pg, '#compare-bridge') == '{"g":0,"a":0,"b":1}')
    pg.keyboard.press('Escape'); pg.set_viewport_size({'width':800,'height':700}); pg.wait_for_timeout(700)
    pg.click('#tab-story'); pg.wait_for_timeout(500)
    ok('narrow: sidebar stacks above gallery', rect(pg,S+'.mainc')['t'] > rect(pg,S+'.side')['b'] - 5)
    print('page errors:', errs)
    b.close()
bad = [k for k, v in R.items() if not v]
print('\nFAILED:', bad, '| screenshots in', WORK)
sys.exit(1 if bad else 0)
